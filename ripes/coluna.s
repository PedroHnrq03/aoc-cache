    la   s0, matriz     # s0 = endereco base da matriz
    li   s1, 32         # s1 = N
    li   s2, 0          # s2 = soma

    li   t1, 0          # j = 0   (laco de FORA)
laco_fora:
    li   t0, 0          # i = 0   (laco de DENTRO)
laco_dentro:
    mul  t2, t0, s1     # t2 = i * N
    add  t2, t2, t1     # t2 = i * N + j
    slli t2, t2, 2      # t2 = (i * N + j) * 4   -> deslocamento em bytes
    add  t2, t2, s0     # t2 = endereco de m[i][j]
